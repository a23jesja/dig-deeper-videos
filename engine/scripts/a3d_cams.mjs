// Writes src/craft/alcatraz3d/cams.ts: every shot's per-frame projection that Blender has written (cam/<id>.json), as one import map.
//   node scripts/a3d_cams.mjs
import fs from "node:fs";
const dir = "src/craft/alcatraz3d/cam", ids = fs.readdirSync(dir).filter((f) => /^n\d\d\.json$/.test(f)).map((f) => f.slice(0, 3)).sort();
fs.writeFileSync("src/craft/alcatraz3d/cams.ts", "// generated by scripts/a3d_cams.mjs: each shot's projection world -> pixel, frame by frame (written by Blender)\n" +
  ids.map((id) => `import ${id.toUpperCase()} from "./cam/${id}.json";`).join("\n") + "\n" +
  `export const CAMS: Record<string, number[][][]> = { ${ids.map((id) => `${id}: ${id.toUpperCase()}.frames`).join(", ")} };\n`);
console.log("cams:", ids.join(" "));
